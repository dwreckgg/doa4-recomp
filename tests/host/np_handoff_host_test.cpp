struct CvarDef {
  std::string type;           // BOOL, STRING, INT32, UINT32, DOUBLE ... (the macro's suffix)
  std::string default_token;  // the second macro argument as written
};

// The cvars defined by REXCVAR_DEFINE_<TYPE>( name, default ... in the .cpp/.h/.cc files below `root` (the definition
// may continue on the next line, as audio_maxqframes' does). The first definition of a name counts.
static std::map<std::string, CvarDef> ScanCvars(const std::filesystem::path& root, size_t* files) {
  std::map<std::string, CvarDef> defs;
  std::error_code ec;
  *files = 0;
  for (std::filesystem::recursive_directory_iterator it(root, std::filesystem::directory_options::skip_permission_denied, ec), end;
       !ec && it != end; it.increment(ec)) {
    if (!it->is_regular_file(ec)) continue;
    const std::string ext = it->path().extension().string();
    if (ext != ".cpp" && ext != ".h" && ext != ".cc") continue;
    std::ifstream in(it->path(), std::ios::binary);
    const std::string text((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    ++*files;
    static const std::string kKey = "REXCVAR_DEFINE_";
    auto skip_space = [&](size_t p) {
      while (p < text.size() && std::isspace(static_cast<unsigned char>(text[p]))) ++p;
      return p;
    };
    for (size_t at = text.find(kKey); at != std::string::npos; at = text.find(kKey, at + 1)) {
      size_t p = at + kKey.size();
      const size_t type_begin = p;
      while (p < text.size() && (std::isupper(static_cast<unsigned char>(text[p])) || std::isdigit(static_cast<unsigned char>(text[p])) || text[p] == '_')) ++p;
      const std::string type = text.substr(type_begin, p - type_begin);
      if (p >= text.size() || text[p] != '(') continue;
      p = skip_space(p + 1);
      size_t q = p;
      while (q < text.size() && (std::isalnum(static_cast<unsigned char>(text[q])) || text[q] == '_')) ++q;
      if (q == p) continue;
      const std::string name = text.substr(p, q - p);
      // the second argument: up to a comma or the closing parenthesis outside quotes and nested parentheses
      std::string token;
      p = skip_space(q);
      if (p < text.size() && text[p] == ',') {
        p = skip_space(p + 1);
        int depth = 0;
        bool quoted = false;
        for (; p < text.size(); ++p) {
          const char c = text[p];
          if (quoted) {
            token += c;
            if (c == '\\' && p + 1 < text.size()) token += text[++p];
            else if (c == '"') quoted = false;
            continue;
          }
          if (c == '"') quoted = true;
          else if (c == '(') ++depth;
          else if (c == ')' && depth == 0) break;
          else if (c == ')') --depth;
          else if (c == ',' && depth == 0) break;
          token += c;
        }
        while (!token.empty() && std::isspace(static_cast<unsigned char>(token.back()))) token.pop_back();
      }
      defs.emplace(name, CvarDef{type, token});
    }
  }
  return defs;
}

static void TestSdkNames(const std::string& sdk_src, const std::string& port_src) {
  Group("census: every cvar the SDK and the port define is classified, every classified name is defined, the total is pinned");
  CHECK(!sdk_src.empty() && !port_src.empty());  // the runner passes --sdk-src and --port-src; a missing one is a failure, not a skip
  if (sdk_src.empty() || port_src.empty()) return;
  size_t sdk_files = 0, port_files = 0;
  const std::map<std::string, CvarDef> sdk = ScanCvars(sdk_src, &sdk_files);
  const std::map<std::string, CvarDef> port = ScanCvars(port_src, &port_files);
  if (g_verbose) std::printf("sdk: %zu files, %zu cvars; port: %zu files, %zu cvars\n", sdk_files, sdk.size(), port_files, port.size());
  // non-vacuity floors and the scanner's own controls
  CHECK(sdk_files > 300 && sdk.size() > 150);
  CHECK(port_files > 20 && port.size() >= 7);
  CHECK(sdk.count("vsync") && sdk.count("user_language"));
  CHECK(sdk.count("audio_maxqframes"));  // a definition whose name is on the line after the macro
  CHECK(sdk.count("headless"));          // defined, deliberately not carried (the session forces it)
  CHECK(port.count("doa4_tag_all_stages"));
  CHECK(!sdk.count("no_such_cvar_xyz") && !port.count("no_such_cvar_xyz"));

  // the two lists: no repeats, no overlap, and together the pinned total
  std::set<std::string> carried(kSdkNames, kSdkNames + kSdkCount), not_carried;
  for (const NotCarried& nc : kSdkNotCarried) {
    CHECK(not_carried.insert(nc.name).second);
    CHECK(nc.family[0] != '\0');
  }
  CHECK(carried.size() == kSdkCount);
  CHECK(not_carried.size() == kSdkNotCarriedCount);
  for (const std::string& n : carried) CHECK(!not_carried.count(n));
  CHECK(kSdkCount + kSdkNotCarriedCount == kSdkTotal);
  CHECK(sdk.size() == kSdkTotal);

  // every defined name is in exactly one list; every listed name is defined
  for (const auto& d : sdk) {
    g_ctx = d.first;
    CHECK(carried.count(d.first) + not_carried.count(d.first) == 1);
  }
  for (const std::string& n : carried) {
    g_ctx = n;
    CHECK(sdk.count(n) == 1);
  }
  for (const std::string& n : not_carried) {
    g_ctx = n;
    CHECK(sdk.count(n) == 1);
  }
  g_ctx.clear();
  CHECK(not_carried.count("headless") == 1);  // the one deliberate exclusion

  // the port: its cvars are the Extras tweaks (carried through the tweaks module) and the listed host-only names
  std::set<std::string> port_expected(kPortNotCarried, kPortNotCarried + kPortNotCarriedCount);
  for (const doa4::tweaks::Tweak& t : doa4::tweaks::AllTweaks()) CHECK(port_expected.insert(t.cvar).second);
  CHECK(port_expected.size() == kPortNotCarriedCount + doa4::tweaks::AllTweaks().size());
  for (const auto& d : port) {
    g_ctx = d.first;
    CHECK(port_expected.count(d.first) == 1);
  }
  for (const std::string& n : port_expected) {
    g_ctx = n;
    CHECK(port.count(n) == 1);
  }
  g_ctx.clear();
  CHECK(port.size() == port_expected.size());

  // every carried name is a cvar of the SDK or the port (a typo would refuse every session)
  for (const std::string& n : ho::GuestSettingNames()) {
    g_ctx = n;
    CHECK(sdk.count(n) + port.count(n) >= 1);
  }
  g_ctx.clear();

  Group("trust: each trust-class default is the default the SDK defines (the registry prints a bool as true or false, a string as itself)");
  for (const Trusted& t : kTrusted) {
    g_ctx = t.name;
    const auto it = sdk.find(t.name);
    CHECK(it != sdk.end());
    if (it == sdk.end()) continue;
    const std::string def = t.default_text;
    if (it->second.type == "BOOL") {
      CHECK(def == "true" || def == "false");
      CHECK(it->second.default_token == def);
    } else if (it->second.type == "STRING") {
      CHECK(it->second.default_token == "\"" + def + "\"");
    } else {  // an integer type: the decimal text
      CHECK(it->second.default_token == def);
    }
  }
  g_ctx.clear();
  auto token = [&](const char* n) { auto it = sdk.find(n); return it == sdk.end() ? std::string("<missing>") : it->second.default_token; };
  CHECK(token("allow_game_relative_writes") == "false");  // a positive control of the extraction
  CHECK(token("cl") == "\"\"" && token("rexcrt_heap_size_mb") == "256");
}

